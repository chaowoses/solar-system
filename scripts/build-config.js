"use strict";
// Turns the TEACHER_PIN environment variable into public/js/config.js.
// Only a salted PBKDF2 hash is written; the PIN itself never ships to the site.
// Runs automatically before `firebase deploy` (see firebase.json), `npm run dev`
// and `npm test`.
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const envFile = path.join(root, ".env");
if (!process.env.TEACHER_PIN && fs.existsSync(envFile)) {
  for (const line of fs.readFileSync(envFile, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*TEACHER_PIN\s*=\s*(.*?)\s*$/);
    if (m) process.env.TEACHER_PIN = m[1].replace(/^["']|["']$/g, "");
  }
}

const pin = process.env.TEACHER_PIN;
if (!pin) {
  console.error("TEACHER_PIN is not set. Put it in .env (TEACHER_PIN=...) or export it before running.");
  process.exit(1);
}

const ITERATIONS = 250000;
const salt = crypto.randomBytes(16);
const hash = crypto.pbkdf2Sync(pin, salt, ITERATIONS, 32, "sha256");

const out = `// Generated by scripts/build-config.js. Do not edit or commit.
export const PIN_CHECK = {
  salt: "${salt.toString("hex")}",
  iterations: ${ITERATIONS},
  hash: "${hash.toString("hex")}",
};
`;
fs.writeFileSync(path.join(root, "public", "js", "config.js"), out);
console.log("Wrote public/js/config.js (PIN hash only).");
